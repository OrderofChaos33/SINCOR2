"""
Harvest Moon claim API blueprint.

Endpoints:
    GET  /api/harvest/status             — public stats (claims, remaining, window)
    GET  /api/harvest/eligibility        — check a wallet address
    POST /api/harvest/claim              — serve Merkle proof for on-chain claim
    POST /api/harvest/conversion_event   — log a post-claim conversion event

All endpoints emit structured JSON log events for observability.
Rate limiting is applied per the existing SINCOR patterns.
No secrets are exposed.  Claim proofs are only served once to the claimant.
"""

from __future__ import annotations

import json
import logging
import os
import sqlite3
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional

from flask import Blueprint, current_app, g, jsonify, request

logger = logging.getLogger(__name__)

harvest_bp = Blueprint("harvest", __name__, url_prefix="/api/harvest")

# ─────────────────────────────────────────────────────────────────────────────
# Database helpers (sqlite3 — same pattern as mvp_app.py)
# ─────────────────────────────────────────────────────────────────────────────

_DB_ENV = "HARVEST_DB_PATH"
_DEFAULT_DB = "data/harvest.db"


def _db_path() -> str:
    return os.environ.get(_DB_ENV, _DEFAULT_DB)


def _get_db() -> sqlite3.Connection:
    if "harvest_db" not in g:
        db = sqlite3.connect(_db_path())
        db.row_factory = sqlite3.Row
        g.harvest_db = db
    return g.harvest_db


def init_harvest_db(db_path: Optional[str] = None) -> None:
    """Create tables if they don't exist.  Safe to call on every startup."""
    path = db_path or _db_path()
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    try:
        conn.executescript("""
            CREATE TABLE IF NOT EXISTS harvest_eligibility (
                address        TEXT    PRIMARY KEY,
                eligible       INTEGER NOT NULL DEFAULT 0,
                amount_wei     TEXT    NOT NULL DEFAULT '0',
                checked_at     TEXT    NOT NULL,
                notes          TEXT
            );

            CREATE TABLE IF NOT EXISTS harvest_claims (
                id             TEXT    PRIMARY KEY,
                address        TEXT    UNIQUE NOT NULL,
                amount_wei     TEXT    NOT NULL,
                proof_json     TEXT    NOT NULL,
                proof_served   INTEGER NOT NULL DEFAULT 0,
                claimed_onchain INTEGER NOT NULL DEFAULT 0,
                created_at     TEXT    NOT NULL,
                updated_at     TEXT    NOT NULL
            );

            CREATE TABLE IF NOT EXISTS harvest_conversion_events (
                id             TEXT    PRIMARY KEY,
                address        TEXT    NOT NULL,
                event_type     TEXT    NOT NULL,
                metadata_json  TEXT,
                created_at     TEXT    NOT NULL
            );

            CREATE INDEX IF NOT EXISTS idx_claims_address
                ON harvest_claims(address);
            CREATE INDEX IF NOT EXISTS idx_conversion_address
                ON harvest_conversion_events(address);
        """)
        conn.commit()
    finally:
        conn.close()


# ─────────────────────────────────────────────────────────────────────────────
# Proof store (loaded from proofs.json generated by generate_harvest_merkle.py)
# ─────────────────────────────────────────────────────────────────────────────

_PROOF_CACHE: Optional[Dict[str, Any]] = None


def _load_proofs() -> Dict[str, Any]:
    global _PROOF_CACHE
    if _PROOF_CACHE is not None:
        return _PROOF_CACHE
    proofs_path = os.environ.get("HARVEST_PROOFS_PATH", "")
    if not proofs_path or not Path(proofs_path).exists():
        logger.warning("HARVEST_PROOFS_PATH not set or file missing — eligibility checks disabled")
        return {}
    with open(proofs_path, encoding="utf-8") as f:
        _PROOF_CACHE = json.load(f)
    logger.info("Loaded %d harvest proofs from %s", len(_PROOF_CACHE), proofs_path)
    return _PROOF_CACHE


# ─────────────────────────────────────────────────────────────────────────────
# Structured logging helper
# ─────────────────────────────────────────────────────────────────────────────

def _emit(event: str, **kwargs: Any) -> None:
    payload = {
        "event": event,
        "request_id": getattr(g, "request_id", str(uuid.uuid4())),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        **kwargs,
    }
    logger.info(json.dumps(payload))


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

def _normalize_address(raw: str) -> Optional[str]:
    """Basic hex address normalization (lowercase, with 0x prefix)."""
    addr = raw.strip().lower()
    if not addr.startswith("0x"):
        addr = "0x" + addr
    if len(addr) != 42 or not all(c in "0123456789abcdef" for c in addr[2:]):
        return None
    return addr


def _page_enabled() -> bool:
    return os.environ.get("HARVEST_PAGE_ENABLED", "true").lower() not in ("false", "0", "off")


def _require_page_enabled():
    if not _page_enabled():
        return jsonify({"error": "harvest_unavailable", "message": "Harvest claim is not active"}), 503
    return None


