@harvest_bp.get("/status")
def harvest_status():
    """Public stats: total claims, remaining allocation, window state."""
    blocked = _require_page_enabled()
    if blocked:
        return blocked

    db = _get_db()
    total_claims = db.execute(
        "SELECT COUNT(*) FROM harvest_claims WHERE claimed_onchain = 1"
    ).fetchone()[0]
    unique_wallets = db.execute(
        "SELECT COUNT(DISTINCT address) FROM harvest_claims WHERE claimed_onchain = 1"
    ).fetchone()[0]

    proofs = _load_proofs()

    data = {
        "claim_window_open": _page_enabled(),
        "total_claims": total_claims,
        "unique_wallets": unique_wallets,
        "eligible_count": len(proofs),
        "contract_address": os.environ.get("HARVEST_CONTRACT_ADDRESS", ""),
        "token_address": os.environ.get("SINC_TOKEN_ADDRESS", "0x9C8cd8d3961F445D653713dE65C6578bE11668e7"),
    }

    _emit("harvest_status_check", **data)
    return jsonify(data)


@harvest_bp.get("/eligibility")
def check_eligibility():
    """Check whether a wallet address is eligible to claim.

    Query params:
        address — 0x-prefixed wallet address
    """
    blocked = _require_page_enabled()
    if blocked:
        return blocked

    raw = request.args.get("address", "").strip()
    if not raw:
        return jsonify({"error": "missing_address", "message": "address query parameter required"}), 400

    # Accept checksummed or lowercase
    # We store in proofs.json as checksummed; do case-insensitive lookup
    proofs = _load_proofs()
    matched_key: Optional[str] = None
    for key in proofs:
        if key.lower() == raw.lower():
            matched_key = key
            break

    if matched_key is None:
        _emit("harvest_eligibility_check", address=raw, eligible=False, reason="not_in_tree")
        return jsonify({"address": raw, "eligible": False, "reason": "not_in_tree"})

    entry = proofs[matched_key]

    # Check if already claimed (in our DB)
    db = _get_db()
    claim_row = db.execute(
        "SELECT claimed_onchain FROM harvest_claims WHERE lower(address) = ?",
        (raw.lower(),),
    ).fetchone()

    already_claimed = bool(claim_row and claim_row["claimed_onchain"])

    _emit(
        "harvest_eligibility_check",
        address=raw,
        eligible=not already_claimed,
        already_claimed=already_claimed,
        amount_wei=entry["amount"],
    )

    return jsonify({
        "address": raw,
        "eligible": not already_claimed,
        "already_claimed": already_claimed,
        "amount": entry.get("amount_ether", ""),
        "amount_wei": entry["amount"],
        "message": (
            "Already claimed" if already_claimed
            else "Eligible — call /api/harvest/claim to receive proof"
        ),
    })


@harvest_bp.post("/claim")
def initiate_claim():
    """Serve Merkle proof so the wallet can call HarvestClaim.claim() on-chain.

    Body JSON:
        address — 0x-prefixed wallet address

    Returns the proof array and amount for the on-chain call.
    Proof is recorded as served; does not itself trigger on-chain tx.
    """
    blocked = _require_page_enabled()
    if blocked:
        return blocked

    payload = request.get_json(silent=True) or {}
    raw = payload.get("address", "").strip()
    if not raw:
        return jsonify({"error": "missing_address", "message": "address field required"}), 400

    proofs = _load_proofs()
    matched_key: Optional[str] = None
    for key in proofs:
        if key.lower() == raw.lower():
            matched_key = key
            break

    if matched_key is None:
        _emit("harvest_claim_request", address=raw, success=False, reason="not_eligible")
        return jsonify({"error": "not_eligible", "message": "Address not in claim tree"}), 403

    entry = proofs[matched_key]
    db = _get_db()

    # Check already claimed
    claim_row = db.execute(
        "SELECT id, claimed_onchain FROM harvest_claims WHERE lower(address) = ?",
        (raw.lower(),),
    ).fetchone()

    if claim_row and claim_row["claimed_onchain"]:
        _emit("harvest_claim_request", address=raw, success=False, reason="already_claimed")
        return jsonify({"error": "already_claimed", "message": "This address has already claimed"}), 409

    now = datetime.now(timezone.utc).isoformat()
    claim_id = str(uuid.uuid4())

    if claim_row is None:
        db.execute(
            """INSERT INTO harvest_claims
               (id, address, amount_wei, proof_json, proof_served, claimed_onchain, created_at, updated_at)
               VALUES (?, ?, ?, ?, 1, 0, ?, ?)""",
            (
                claim_id,
                matched_key,
                entry["amount"],
                json.dumps(entry["proof"]),
                now,
                now,
            ),
        )
    else:
        db.execute(
            "UPDATE harvest_claims SET proof_served=1, updated_at=? WHERE lower(address)=?",
            (now, raw.lower()),
        )
    db.commit()

    _emit(
        "harvest_claim_request",
        address=raw,
        success=True,
        amount_wei=entry["amount"],
        proof_length=len(entry["proof"]),
    )

    return jsonify({
        "success": True,
        "address": matched_key,
        "amount_wei": entry["amount"],
        "amount": entry.get("amount_ether", ""),
        "proof": entry["proof"],
        "contract_address": os.environ.get("HARVEST_CONTRACT_ADDRESS", ""),
        "message": (
            "Proof served. Call HarvestClaim.claim(proof, amount) with this data. "
            "Utility access credits only — no investment value."
        ),
    })


@harvest_bp.post("/confirm")
def confirm_onchain():
    """Mark a claim as confirmed on-chain (called by agent after monitoring tx).

    Body JSON:
        address — wallet address
        tx_hash — on-chain transaction hash
    """
    payload = request.get_json(silent=True) or {}
    raw = (payload.get("address") or "").strip()
    tx_hash = (payload.get("tx_hash") or "").strip()

    if not raw or not tx_hash:
        return jsonify({"error": "missing_fields", "message": "address and tx_hash required"}), 400

    db = _get_db()
    now = datetime.now(timezone.utc).isoformat()
    updated = db.execute(
        """UPDATE harvest_claims
           SET claimed_onchain=1, updated_at=?
           WHERE lower(address)=?""",
        (now, raw.lower()),
    ).rowcount
    db.commit()

    _emit("harvest_claim_confirmed", address=raw, tx_hash=tx_hash)

    if updated == 0:
        return jsonify({"error": "not_found", "message": "No pending claim for address"}), 404

    return jsonify({"success": True, "address": raw, "tx_hash": tx_hash})


@harvest_bp.post("/conversion_event")
def log_conversion():
    """Log a post-claim conversion event (plan upgrade, paid skill call, etc.).

    Body JSON:
        address    — wallet address
        event_type — e.g. "plan_upgrade", "paid_skill_call", "demo_scheduled"
        metadata   — optional dict of additional context
    """
    payload = request.get_json(silent=True) or {}
    raw = (payload.get("address") or "").strip()
    event_type = (payload.get("event_type") or "").strip()

    if not raw or not event_type:
        return jsonify({"error": "missing_fields", "message": "address and event_type required"}), 400

    db = _get_db()
    now = datetime.now(timezone.utc).isoformat()
    event_id = str(uuid.uuid4())

    metadata = payload.get("metadata")
    db.execute(
        """INSERT INTO harvest_conversion_events
           (id, address, event_type, metadata_json, created_at)
           VALUES (?, ?, ?, ?, ?)""",
        (event_id, raw.lower(), event_type, json.dumps(metadata) if metadata else None, now),
    )
    db.commit()

    _emit(
        "harvest_conversion_event",
        address=raw,
        event_type=event_type,
        event_id=event_id,
    )

    return jsonify({"success": True, "event_id": event_id})
