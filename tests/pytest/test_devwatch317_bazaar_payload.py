"""Dev-watch 317 — Bazaar discovery extension completeness + settle payload.

SWARM seller log (2026-09-28, updated 2026-10-02): twelve settled test
purchases never appeared in Coinbase's Bazaar. Two seller-side causes:

1. Its discovery extension had ``info.input`` but NO ``schema`` —
   Coinbase's validator rejects that as an invalid discovery
   configuration.
2. The Bazaar indexer reads discovery data from
   ``PaymentPayload.resource`` and ``PaymentPayload.extensions`` at
   settle time, and the official client does not copy them there — an
   adapter forwarding only ``x402Version`` / ``accepted`` / ``payload``
   silently drops the indexing data.

Our state before this fix: ``build_payment_payload`` (the single 402
constructor) carried NO ``extensions`` key at all.

Fix under test:
* ``build_payment_payload`` attaches ``extensions.bazaar`` to every 402,
  generated by ONE helper (``build_bazaar_discovery_extension``) so the
  shape cannot drift per-resource: ``info.input`` describing the paid
  call AND a full ``schema`` whose ``properties.input.properties.body``
  is the resource's real input schema.
* ``validate_bazaar_extension`` checks the documented validator
  requirements locally (schema present, types sane, info validates
  against the schema).
* ``build_facilitator_payload`` — the payload handed to the
  facilitator/settle step — copies ``resource`` and ``extensions``
  explicitly and FAILS CLOSED when either is missing/invalid, instead
  of silently dropping the indexing data.
"""
from __future__ import annotations

import copy

import pytest

import sincor2.x402_payments as x402


# ---------------------------------------------------------------------------
# (a) 402 responses carry a complete discovery extension, helper-generated
# ---------------------------------------------------------------------------

def test_every_resource_402_carries_complete_bazaar_extension():
    resources = x402.list_resources()
    assert resources, "pricing config must define resources"
    for resource in resources:
        rid = resource["id"]
        payload = x402.build_payment_payload(resource, rid, "x402-test317")
        ext = payload.get("extensions")
        assert ext is not None, f"{rid}: 402 payload has no extensions"
        errors = x402.validate_bazaar_extension(ext)
        assert errors == [], f"{rid}: invalid bazaar extension: {errors}"
        bazaar = ext["bazaar"]
        # info.input present and sane (the half SWARM had).
        info_input = bazaar["info"]["input"]
        assert info_input["type"] == "http"
        assert info_input["method"] in ("GET", "POST")
        # schema present and complete (the half SWARM was missing).
        schema = bazaar["schema"]
        assert schema["type"] == "object"
        assert "input" in schema["required"]
        body_schema = schema["properties"]["input"]["properties"]["body"]
        assert body_schema["type"] == "object"
        assert isinstance(body_schema["properties"], dict)


def test_bazaar_info_validates_against_its_own_schema():
    jsonschema = pytest.importorskip("jsonschema")
    for resource in x402.list_resources():
        payload = x402.build_payment_payload(
            resource, resource["id"], "x402-test317")
        bazaar = payload["extensions"]["bazaar"]
        # Coinbase's validator checks info against the declared schema;
        # an info block that fails its own schema is rejected.
        jsonschema.validate(bazaar["info"], bazaar["schema"])


def test_skill_resources_carry_their_real_input_fields():
    # Field names mirror what each serve handler actually reads
    # (mvp_blueprints.billing._paid_skill_dispatch -> skill modules).
    expected = {
        "wallet-sanctions-screen": {"address"},
        "kya-trust-score": {"agent_id", "wallet"},
        "web-search-read": {"mode", "query", "url"},
        "local-business-site-check": {"url", "business_name"},
        "market-data-read": {"pair", "mode"},
        "polymarket-whale-signal": {"wallet", "market_id", "window_minutes"},
        "toa-micro-decision": {"options", "context", "decision_id"},
    }
    for rid, fields in expected.items():
        resource = x402.get_resource(rid)
        assert resource is not None, f"{rid} missing from pricing config"
        payload = x402.build_payment_payload(resource, rid, "x402-test317")
        body_schema = payload["extensions"]["bazaar"]["schema"][
            "properties"]["input"]["properties"]["body"]
        missing = fields - set(body_schema["properties"])
        assert not missing, f"{rid}: input schema missing fields {missing}"
        for name, prop in body_schema["properties"].items():
            assert prop["type"] in (
                "string", "integer", "number", "boolean", "array", "object",
            ), f"{rid}.{name}: insane schema type {prop.get('type')!r}"


def test_create_challenge_402_body_carries_extension(tmp_path, monkeypatch):
    monkeypatch.setenv("SINCOR_DATA_DIR", str(tmp_path))
    ch = x402.create_challenge("wallet-sanctions-screen")
    assert ch["http_status"] == 402
    payment = ch["payment"]
    assert payment["resource"] == "/x402/wallet-sanctions-screen"
    errors = x402.validate_bazaar_extension(payment.get("extensions"))
    assert errors == []


# ---------------------------------------------------------------------------
# Local validator: the SWARM failure shapes are rejected
# ---------------------------------------------------------------------------

def _valid_extension():
    resource = x402.get_resource("wallet-sanctions-screen")
    payload = x402.build_payment_payload(resource, resource["id"], "x402-t")
    return payload["extensions"]


def test_validator_rejects_extension_without_schema():
    ext = copy.deepcopy(_valid_extension())
    del ext["bazaar"]["schema"]  # SWARM failure #1, exactly
    errors = x402.validate_bazaar_extension(ext)
    assert any("schema" in e for e in errors)


def test_validator_rejects_extension_without_info_input():
    ext = copy.deepcopy(_valid_extension())
    del ext["bazaar"]["info"]["input"]
    errors = x402.validate_bazaar_extension(ext)
    assert any("input" in e for e in errors)


def test_validator_rejects_missing_or_empty_extension():
    assert x402.validate_bazaar_extension(None)
    assert x402.validate_bazaar_extension({})
    assert x402.validate_bazaar_extension({"bazaar": {}})


# ---------------------------------------------------------------------------
# (b) The settle/facilitator payload carries resource + extensions intact
# ---------------------------------------------------------------------------

def test_facilitator_payload_preserves_resource_and_extensions():
    resource = x402.get_resource("kya-trust-score")
    payment = x402.build_payment_payload(resource, "kya-trust-score", "x402-t")
    settle_payload = x402.build_facilitator_payload(
        payment, payload_body={"signature": "0xdeadbeef"})
    assert settle_payload["resource"] == payment["resource"]
    assert settle_payload["extensions"] == payment["extensions"]
    assert x402.validate_bazaar_extension(settle_payload["extensions"]) == []
    assert settle_payload["payload"] == {"signature": "0xdeadbeef"}
    # Route fields ride along inside `accepted`, selected from the 402
    # payload (never rebuilt by the adapter).
    assert settle_payload["accepted"]["network"] == payment["network"]
    assert settle_payload["accepted"]["payTo"] == payment["payTo"]


def test_facilitator_payload_fails_closed_without_extensions():
    resource = x402.get_resource("kya-trust-score")
    payment = x402.build_payment_payload(resource, "kya-trust-score", "x402-t")
    stripped = {k: v for k, v in payment.items() if k != "extensions"}
    with pytest.raises(ValueError):
        x402.build_facilitator_payload(stripped)


def test_facilitator_payload_fails_closed_without_resource():
    resource = x402.get_resource("kya-trust-score")
    payment = x402.build_payment_payload(resource, "kya-trust-score", "x402-t")
    stripped = {k: v for k, v in payment.items() if k != "resource"}
    with pytest.raises(ValueError):
        x402.build_facilitator_payload(stripped)


def test_facilitator_payload_fails_closed_on_schemaless_extension():
    resource = x402.get_resource("kya-trust-score")
    payment = x402.build_payment_payload(resource, "kya-trust-score", "x402-t")
    broken = copy.deepcopy(payment)
    del broken["extensions"]["bazaar"]["schema"]
    with pytest.raises(ValueError):
        x402.build_facilitator_payload(broken)
